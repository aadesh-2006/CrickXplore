// Helper to update array with IPL tags and append new players
function processPlayerArray(existing: NormalizedPlayer[], newOnes: NormalizedPlayer[]): NormalizedPlayer[] {
  const updatedExisting = existing.map(player => {
    const meta = EXISTING_IPL_METADATA[player.id];
    if (meta) {
      return {
        ...player,
        ipl2026Team: meta.team,
        ipl2026: {
          team: meta.team,
          role: meta.role,
          isKeyXI: meta.isKeyXI,
          isImpactCandidate: meta.isImpactCandidate,
        },
      };
    }
    return player;
  });

  return [...updatedExisting, ...newOnes];
}

// Format player object into clean TypeScript code
function formatPlayerArrayCode(arrayName: string, players: NormalizedPlayer[]): string {
  const content = `import type { NormalizedPlayer } from '../../types/player';

export const ${arrayName}: NormalizedPlayer[] = ${JSON.stringify(players, null, 2)};
`;
  return content;
}

